D='/home/claude/imyonghanpan/_source/data/'
P=json.load(open(D+'pastq.json'));QI=json.load(open(D+'qimgs.json'));QT=json.load(open(D+'qtext.json'))
P['qs']=[q for q in P['qs'] if q['ex'] not in C]
for ex,L in C.items():
    for i,(a,al,t) in enumerate(L,1):
        assert a in P['areas'] and all(x in P['areas'] for x in al),(ex,i)
        m=re.search(r'\[(\d)점\]',QT[ex][str(i)]);pts=int(m.group(1)) if m else (2 if i<= (4 if ex[-1]=='A' else 2) else 4)
