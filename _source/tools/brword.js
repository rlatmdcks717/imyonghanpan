function koBraille(word){
  if(KABBR[word])return {cells:KABBR[word],gloss:["약어 "+word]};
  const syl=split(word);if(!syl)return null;
  const cells=[],gloss=[];const add=(c,g)=>{cells.push(c);gloss.push(g);};
  for(let i=0;i<syl.length;i++){
    const [c,v,j=""]=syl[i],next=syl[i+1],prev=syl[i-1];
    if(!KCHO[c]&&c!=="ㅇ")return null;                 // 된소리
    if(j&&!KJONG[j])return null;                        // 겹받침 등
    if(!KVOW[v])return null;
    if(c==="ㅇ"&&v==="ㅖ"&&prev&&prev.length===2)return null;            // 모음 뒤 ‘예’
    if(c==="ㅇ"&&v==="ㅐ"&&prev&&prev.length===2&&"ㅑㅘㅜㅝ".includes(prev[1]))return null; // ㅑ·ㅘ·ㅜ·ㅝ 뒤 ‘애’
    if(c==="ㄱ"&&v==="ㅓ"&&j==="ㅅ"){cells.push("456","234");gloss.push("약자 것");continue;}
    if(v==="ㅏ"&&KA[c]){
      if(!j&&next&&next[0]==="ㅇ"&&"ㄴㄷㅌㅍㅎ".includes(c))return null;  // ‘나·다·타·파·하’ 뒤 모음
      add(KA[c],"약자 "+compose(c,"ㅏ"));
      if(j)add(KJONG[j],j==="ㅆ"?"약자 ㅆ받침":"받침 "+j);
      continue;
    }
    if(c!=="ㅇ")add(KCHO[c],"초성 "+c);
    let rk=v+j;
    if(v==="ㅓ"&&j==="ㅇ"&&"ㅅㅈㅊ".includes(c))rk="ㅕㅇ";              // 성·정·청
    if(j&&KRIME[rk]){add(KRIME[rk],"약자 "+compose("ㅇ",rk[0],rk[1]));continue;}
    KVOW[v].forEach((d,k)=>add(d,k?"":"모음 "+v));
    if(j)add(KJONG[j],j==="ㅆ"?"약자 ㅆ받침":"받침 "+j);
  }
  return {cells,gloss:gloss.filter(Boolean)};
}
